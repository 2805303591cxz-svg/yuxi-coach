/* 档位推荐规则：按学分线性化（推免绩点是学分加权，时间分配就该跟学分走）
   5.5/6 学分 → 深 35'    3~4 学分 → 标准 25'    1~2.9 学分 → 快 10'    0.3~0.9 学分 → 轻 5'
   重要性只做微调：core 不降档，light 不升档。 */
window.recommendLevel = function (importance, credits) {
  var c = Number(credits) || 0;
  var lv = c >= 4.5 ? 'deep' : (c >= 3 ? 'standard' : (c >= 1 ? 'quick' : 'light'));
  if (importance === 'light' && lv !== 'deep') return 'light';
  if (importance === 'core' && lv === 'quick') return 'standard';
  return lv;
};

